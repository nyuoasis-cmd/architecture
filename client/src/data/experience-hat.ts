/** 강 기본 + 문항 덮어쓰기를 합쳐 돌려준다. 둘 다 없으면 undefined — 머리표 없이 뜬다. */
export function getExperienceHat(chapterId: number, qaId: string): ExperienceHat | undefined {
  const base = HAT_BY_CHAPTER[chapterId];
  const override = HAT_BY_QA[qaId];
  if (!base) return undefined;
  return override ? { ...base, ...override } : base;
}
