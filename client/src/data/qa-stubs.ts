const BASE_QA_STUBS: QaStub[] = QA_COUNTS.flatMap((count, chapterIndex) => {
  const chapterId = chapterIndex + 1;
  return Array.from({ length: count }, (_, idx) => {
    const order = idx + 1;
    if (chapterId === 1) {
      return CHAPTER_ONE_QAS[order - 1]!;
    }
    if (chapterId === 2) {
      return CHAPTER_TWO_QAS[order - 1]!;
    }
    if (chapterId === 3) {
      return CHAPTER_THREE_QAS[order - 1]!;
    }
    if (chapterId === 4) {
      return CHAPTER_FOUR_QAS[order - 1]!;
    }
    if (chapterId === 5) {
      return CHAPTER_FIVE_QAS[order - 1]!;
    }
    if (chapterId === 6) {
      return CHAPTER_SIX_QAS[order - 1] ?? createStubQa(chapterId, order);
    }
    if (chapterId === 7) {
      return CHAPTER_SEVEN_QAS[order - 1]!;
    }
    if (chapterId === 8) {
      return CHAPTER_EIGHT_QAS[order - 1]!;
    }
    if (chapterId === 9) {
      return CHAPTER_NINE_QAS[order - 1]!;
    }
    if (chapterId === 10) {
      return CHAPTER_TEN_QAS[order - 1]!;
    }

    const stub = createStubQa(chapterId, order);
    return stub;
  });
});

export const QA_STUBS: QaStub[] = [...BASE_QA_STUBS, ...VIBE_QAS];

export function getQaById(qaId: string) {
  return QA_STUBS.find((qa) => qa.id === qaId);
}

export function getChapterById(chapterId: number) {
  return CHAPTERS.find((chapter) => chapter.id === chapterId);
}

export function getQasByChapterId(chapterId: number) {
  return QA_STUBS.filter((qa) => qa.chapterId === chapterId).sort((a, b) => a.order - b.order);
}
